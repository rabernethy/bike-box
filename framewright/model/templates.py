"""Design templates: ready-made starting designs.

Built-in templates live in ``framewright/data/templates/*.fwd`` (generated by
``tools/make_templates.py``); user templates are ordinary design files in
``<config>/templates/*.fwd`` (see :func:`framewright.model.library.config_dir`).
Nothing is created on disk until :func:`save_user_template` is called.

A template's display name is ``extras["meta"]["template_name"]`` (set when a
user saves one), else the design title, else the file name.  Its description
is ``extras["meta"]["description"]``.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path

from .design import FILE_SUFFIX, Design
from .library import config_dir

BUILTIN_DIR = Path(__file__).resolve().parents[1] / "data" / "templates"


@dataclass(frozen=True)
class TemplateInfo:
    name: str
    path: Path
    description: str
    builtin: bool
    category: str = ""
    slug: str = ""
    order: int = 0


def builtin_dir() -> Path:
    return BUILTIN_DIR


def user_dir() -> Path:
    """Directory for user templates (not created here)."""
    return config_dir() / "templates"


def slugify(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "_", str(name).strip().lower()).strip("_")
    return s or "template"


def _info(path: Path, builtin: bool) -> TemplateInfo | None:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    if not isinstance(data, dict):
        return None
    values = data.get("values") or {}
    meta = (data.get("extras") or {}).get("meta") or {}
    name = str(meta.get("template_name") or values.get("title") or path.stem)
    try:
        order = int(meta.get("order", 0))
    except (TypeError, ValueError):
        order = 0
    return TemplateInfo(name=name, path=path, description=str(meta.get("description") or ""),
                        builtin=builtin, category=str(meta.get("category") or ""), slug=path.stem, order=order)


def _scan(directory: Path, builtin: bool) -> list[TemplateInfo]:
    if not directory.is_dir():
        return []
    out = []
    for p in directory.glob(f"*{FILE_SUFFIX}"):
        info = _info(p, builtin)
        if info is not None:
            out.append(info)
    return out


def list_templates() -> list[TemplateInfo]:
    """Built-in templates (in their curated order) followed by user templates (by name)."""
    builtins = sorted(_scan(builtin_dir(), True), key=lambda t: (t.order, t.name.lower()))
    users = sorted(_scan(user_dir(), False), key=lambda t: t.name.lower())
    return builtins + users


def find_template(name_or_path: str | Path) -> TemplateInfo | None:
    """Look a template up by path, file stem (slug) or display name.  User
    templates take precedence over built-ins with the same name."""
    p = Path(name_or_path)
    if p.suffix and p.is_file():
        return _info(p, builtin=p.resolve().parent == builtin_dir())
    key = str(name_or_path).strip()
    infos = sorted(list_templates(), key=lambda t: t.builtin)        # user first
    for t in infos:
        if t.slug == key or t.slug == slugify(key):
            return t
    low = key.lower()
    for t in infos:
        if t.name.lower() == low:
            return t
    return None


def load_template(name_or_path: str | Path) -> Design:
    """Load a template as a fresh design (timestamps cleared, ``meta['template']`` set)."""
    p = Path(name_or_path)
    if p.suffix and p.is_file():
        d = Design.load(p)
        slug = p.stem
    else:
        info = find_template(name_or_path)
        if info is None:
            raise FileNotFoundError(f"no template named {str(name_or_path)!r}")
        d = Design.load(info.path)
        slug = info.slug
    meta = dict(d.extras.get("meta") or {})
    for k in ("created", "modified", "app_version", "order"):
        meta.pop(k, None)
    meta["template"] = slug
    d.extras["meta"] = meta
    return d


def save_user_template(design: Design, name: str, description: str | None = None) -> Path:
    """Save ``design`` as a user template called ``name``; returns the file path.
    An existing user template with the same name is replaced."""
    d = design.copy()
    meta = dict(d.extras.get("meta") or {})
    meta["template_name"] = str(name)
    if description is not None:
        meta["description"] = str(description)
    meta.pop("order", None)
    d.extras["meta"] = meta
    folder = user_dir()
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / f"{slugify(name)}{FILE_SUFFIX}"
    d.save(path)
    return path


def remove_user_template(name_or_path: str | Path) -> bool:
    """Delete a user template file.  Built-in templates are never removed."""
    info = find_template(name_or_path)
    if info is None or info.builtin:
        return False
    try:
        info.path.unlink()
    except OSError:
        return False
    return True
